#!/usr/bin/env python3
"""Verify the plugin files against RELEASE-MANIFEST.json, and print the liability stamp. Standard library only, no network.

Usage
  python nd_integrity.py verify [--root <plugin folder>] [--manifest <file>] [--json]
      Hash every file the manifest lists (SHA-256) and compare. Reports MISMATCH (changed), MISSING (listed but absent)
      and EXTRA (present in a shipped folder but not listed). Exit 0 all match, 1 any difference, 2 no manifest.
  python nd_integrity.py stamp --confidence <0-100> [--format line|block]
      The standard stamp for replies and documents. The plugin version is read from .claude-plugin/plugin.json and the
      knowledge date from knowledge/pack/PROVENANCE.json at run time; nothing is hard-coded.

The manifest is written by the release packager (nd_package.py build): {"name", "version", "files": {relative path: sha256}}.
Limits: the manifest sits beside the files it describes, so someone who can change both defeats the check; the check also cannot
vouch for this script itself. It detects accidental damage and simple tampering; it is not a signature.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHIP_DIRS = [".claude-plugin", "agents", "skills", "hooks", "registry", "knowledge", "scripts"]
SHIP_FILES = ["README.md", "LICENSE", "RELEASE-NOTES.md", "KNOWN-LIMITS.md"]
IGNORE_PARTS = {"__pycache__", ".git", "node_modules"}
OWNER_ONLY = {"scripts/nd_sync_pack.py", "scripts/nd_scan_internal_rules.py", "scripts/nd_package.py", "knowledge/scan-allow.txt"}
STAMP_TEXT = "Generated by Nelli-Dev {version}, knowledge {knowledge}. Confidence {confidence}%. Human review and testing required before production use. Not a substitute for Znode documentation or support."


def sha256(p: Path) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def verify(root: Path, manifest_path: Path) -> dict:
    manifest = json.loads(manifest_path.read_text(encoding="utf-8-sig"))
    files = manifest.get("files")
    if not isinstance(files, dict) or not files:
        raise ValueError("the manifest has no 'files' table")
    mismatch, missing = [], []
    for rel, want in sorted(files.items()):
        p = root / rel
        if not p.is_file():
            missing.append(rel)
        elif sha256(p) != want:
            mismatch.append(rel)
    extra = []
    listed = set(files)
    candidates = [f for d in SHIP_DIRS if (root / d).is_dir() for f in (root / d).rglob("*") if f.is_file()]
    candidates += [root / f for f in SHIP_FILES if (root / f).is_file()]
    for f in sorted(candidates):
        rel = f.relative_to(root).as_posix()
        if rel in listed or rel in OWNER_ONLY or IGNORE_PARTS & set(f.relative_to(root).parts) or f.suffix.lower() == ".pyc":
            continue
        extra.append(rel)
    return {"name": manifest.get("name"), "version": manifest.get("version"), "checked": len(files), "mismatch": mismatch, "missing": missing,
            "extra": extra, "ok": not (mismatch or missing or extra)}


def plugin_version(root: Path = ROOT) -> str:
    try:
        return str(json.loads((root / ".claude-plugin" / "plugin.json").read_text(encoding="utf-8-sig"))["version"])
    except (OSError, ValueError, KeyError):
        return "unknown version"


def knowledge_date(root: Path = ROOT) -> str:
    try:
        return str(json.loads((root / "knowledge" / "pack" / "PROVENANCE.json").read_text(encoding="utf-8-sig"))["built"])
    except (OSError, ValueError, KeyError):
        return "date unknown"


def stamp(confidence: int, root: Path = ROOT) -> str:
    return STAMP_TEXT.format(version=plugin_version(root), knowledge=knowledge_date(root), confidence=int(confidence))


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    v = sub.add_parser("verify"); v.add_argument("--root"); v.add_argument("--manifest"); v.add_argument("--json", action="store_true")
    s = sub.add_parser("stamp"); s.add_argument("--confidence", type=int, required=True); s.add_argument("--format", choices=["line", "block"], default="line")
    try:
        a = ap.parse_args(argv)
    except SystemExit as e:
        return 2 if e.code else 0
    if a.cmd == "stamp":
        if not 0 <= a.confidence <= 100:
            print("--confidence must be 0 to 100", file=sys.stderr)
            return 2
        text = stamp(a.confidence)
        print(("> " + text) if a.format == "block" else text)
        return 0
    root = Path(a.root).resolve() if a.root else ROOT
    mpath = Path(a.manifest) if a.manifest else root / "RELEASE-MANIFEST.json"
    if not mpath.is_file():
        print(f"no manifest at {mpath}. A release carries RELEASE-MANIFEST.json; a working copy does not. Nothing was verified.", file=sys.stderr)
        return 2
    try:
        res = verify(root, mpath)
    except (OSError, ValueError) as e:
        print(f"cannot read the manifest: {e}", file=sys.stderr)
        return 2
    if a.json:
        print(json.dumps(res, indent=1))
    else:
        for tag, key in (("MISMATCH", "mismatch"), ("MISSING ", "missing"), ("EXTRA   ", "extra")):
            for rel in res[key]:
                print(f"{tag} {rel}")
        print(f"# Integrity: {res['checked']} file(s) checked against the manifest of {res['name']} {res['version']}: "
              + ("all match." if res["ok"] else f"{len(res['mismatch'])} changed, {len(res['missing'])} missing, {len(res['extra'])} extra. Reinstall the plugin from the official source."))
    return 0 if res["ok"] else 1


if __name__ == "__main__":
    sys.exit(main())
